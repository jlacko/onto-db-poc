"""Generate the SQLite schema from the SHACL shapes.

    .venv/bin/python scripts/generate_ddl.py        # writes db/schema.sql

Output: one table per node shape, columns from property shapes (NOT NULL from
sh:minCount, CHECK from ranges, FOREIGN KEY from sh:class), link tables for
many-valued properties, a recursive closure view for any self-referencing
hierarchy (skos:broader), and two metadata tables: the ontology release the
schema was built from, and the data dictionary (scripts/dictionary.py) that ties
every column to the IRI, name, definition and value domain of the concept it records (the "IRI is the join key" rule).
"""
from rdflib import OWL, URIRef

from common import DB_DIR, KRIM, ONTO, load_graph
from dictionary import FIELDS, TECHNICAL_TABLES, build_rows
from shapes_model import read_model, table_order


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def ontology_release():
    g = load_graph(ONTO / "kriminalita.ttl")
    onto = URIRef(str(KRIM).rstrip("#"))
    return str(g.value(onto, OWL.versionInfo)), str(g.value(onto, OWL.versionIRI))


def generate() -> str:
    tables = read_model()
    version, version_iri = ontology_release()
    out = [
        "-- GENERATED by scripts/generate_ddl.py from ontology/shapes.ttl - do not edit.",
        f"-- Ontology release {version} ({version_iri})",
        "PRAGMA foreign_keys = ON;",
        "",
    ]
    link_out = []  # link tables go after all base tables

    for t in table_order(tables):
        lines, fks = [], []
        if t.iri_column:
            lines.append(f"    {t.iri_column} TEXT NOT NULL UNIQUE")
        for c in t.columns:
            parts = [f"    {c.name} {c.sql_type}"]
            if c.primary_key:
                parts.append("PRIMARY KEY")
            elif c.not_null:
                parts.append("NOT NULL")
            for chk in c.checks:
                parts.append(f"CHECK ({chk})")
            lines.append(" ".join(parts))
            if c.references:
                fks.append(f"    FOREIGN KEY ({c.name}) REFERENCES {c.references}({tables[c.references].pk.name})")
        out.append(f"-- {t.target_class}")
        out.append(f"CREATE TABLE {t.name} (\n" + ",\n".join(lines + fks) + "\n);")
        out.append("")

        for link in t.links:
            owner_pk, target_pk = t.pk, tables[link.target_table].pk
            owner_col = f"{t.name}_{owner_pk.name}"
            link_out.append(f"-- {link.path} (many-valued)")
            link_out.append(
                f"CREATE TABLE {link.name} (\n"
                f"    {owner_col} {owner_pk.sql_type} NOT NULL,\n"
                f"    {link.column} {target_pk.sql_type} NOT NULL,\n"
                f"    PRIMARY KEY ({owner_col}, {link.column}),\n"
                f"    FOREIGN KEY ({owner_col}) REFERENCES {t.name}({owner_pk.name}),\n"
                f"    FOREIGN KEY ({link.column}) REFERENCES {link.target_table}({target_pk.name})\n"
                ") WITHOUT ROWID;"
            )
            link_out.append(f"CREATE INDEX {link.name}_{link.column} ON {link.name}({link.column});")
            link_out.append("")

        # Closure view for self-referencing hierarchies (e.g. skos:broader).
        for c in t.columns:
            if c.references == t.name:
                pk = t.pk.name
                out.append(f"-- Transitive closure of {c.path} (depth 0 = the item itself)")
                out.append(
                    f"CREATE VIEW {t.name}_ancestor AS\n"
                    f"WITH RECURSIVE anc({pk}, ancestor_{pk}, depth) AS (\n"
                    f"    SELECT {pk}, {pk}, 0 FROM {t.name}\n"
                    f"    UNION ALL\n"
                    f"    SELECT anc.{pk}, p.{c.name}, anc.depth + 1\n"
                    f"    FROM anc JOIN {t.name} p ON p.{pk} = anc.ancestor_{pk}\n"
                    f"    WHERE p.{c.name} IS NOT NULL\n"
                    f")\nSELECT {pk}, ancestor_{pk}, depth FROM anc;"
                )
                out.append("")

    out.extend(link_out)
    out.append("-- Index for period questions (the history is continuous over report time)")
    out.append("CREATE INDEX offence_record_report ON offence_record(report_datetime);")
    out.append("")
    out.append("-- Technical tables: loader bookkeeping, not part of the domain model (scripts/dictionary.py)")
    for tname, (desc, cols) in TECHNICAL_TABLES.items():
        out.append(f"-- {desc}")
        out.append(f"CREATE TABLE {tname} (\n" + ",\n".join(f"    {c} {sql}" for c, sql, *_ in cols) + "\n);")
    out.append("")
    out.append("-- Metadata: which ontology release this schema realises")
    out.append("CREATE TABLE meta_release (\n    ontology_version TEXT NOT NULL,\n"
               "    ontology_version_iri TEXT NOT NULL,\n    generated_from TEXT NOT NULL\n);")
    out.append(f"INSERT INTO meta_release VALUES ({q(version)}, {q(version_iri)}, 'ontology/shapes.ttl');")
    out.append("")
    out.append("-- Data dictionary (ISO/IEC 11179 data elements), generated by scripts/dictionary.py.")
    out.append("-- Every column points back to the concept it records; see FIELDS there for each field's source.")
    cols = ",\n".join(f"    {f} TEXT" for f, _, _ in FIELDS)
    out.append(f"CREATE TABLE meta_column (\n{cols},\n    PRIMARY KEY (table_name, column_name)\n);")
    names = ", ".join(f for f, _, _ in FIELDS)
    for row in build_rows():
        out.append(f"INSERT INTO meta_column ({names}) VALUES ("
                   + ", ".join(q(row.get(f, "") or "") for f, _, _ in FIELDS) + ");")
    out.append("")
    return "\n".join(out)


def main():
    DB_DIR.mkdir(exist_ok=True)
    path = DB_DIR / "schema.sql"
    path.write_text(generate(), encoding="utf-8")
    print(f"wrote {path.relative_to(DB_DIR.parent)}")


if __name__ == "__main__":
    main()
