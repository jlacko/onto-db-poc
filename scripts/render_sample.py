"""Render the sample data as a readable Markdown table for answering CQs by hand.

    .venv/bin/python scripts/render_sample.py     # writes ontology/tests/sample-data.md
"""
from rdflib import RDF, SKOS
from rdflib.namespace import DCTERMS

from common import KRIM, TESTS, load_graph, model_files


def label(g, c, lang="en"):
    for l in g.objects(c, SKOS.prefLabel):
        if l.language == lang:
            return str(l)
    return ""


def code(g, c):
    return int(g.value(c, SKOS.notation))


def render() -> str:
    g = load_graph(*model_files(), TESTS / "sample-data.ttl")
    recs = sorted(g.subjects(RDF.type, KRIM.OffenceRecord), key=lambda r: int(g.value(r, DCTERMS.identifier)))
    out = [
        "# Sample data (test suite)",
        "",
        "GENERATED by `scripts/render_sample.py` from `sample-data.ttl`. Do not edit;",
        "change the Turtle file and regenerate (validate.py checks it is current).",
        "",
        "Use this table to answer the competency questions marked ✍ in",
        "[`../competency-questions.md`](../competency-questions.md).",
        "",
        "## Records",
        "",
        "| record | reported at | lat | lon | municipal police | state | relevance | types | state as of |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    used_types = set()
    for r in recs:
        st, rel = g.value(r, KRIM.hasClearanceState), g.value(r, KRIM.hasLocationRelevance)
        types = sorted(g.objects(r, KRIM.hasOffenceType), key=lambda t: code(g, t))
        used_types |= set(types)
        out.append("| " + " | ".join([
            str(g.value(r, DCTERMS.identifier)),
            str(g.value(r, KRIM.reportDateTime)).replace("T", " "),
            str(g.value(r, KRIM.anonymisedLatitude)),
            str(g.value(r, KRIM.anonymisedLongitude)),
            "yes" if g.value(r, KRIM.recordedByMunicipalPolice).toPython() else "no",
            f"{code(g, st)} {label(g, st)}",
            f"{code(g, rel)} {label(g, rel)}",
            ", ".join(str(code(g, t)) for t in types),
            str(g.value(r, KRIM.stateAsOf)).replace("T", " "),
        ]) + " |")

    out += ["", "## Offence types used above", "",
            "A record carries a type together with all its broader types. *Category* = a type with no broader type.",
            "", "| code | label | broader (path to category) |", "|---|---|---|"]
    for t in sorted(used_types, key=lambda t: code(g, t)):
        path, b = [], g.value(t, SKOS.broader)
        while b is not None:
            path.append(f"{code(g, b)} {label(g, b)}")
            b = g.value(b, SKOS.broader)
        out.append(f"| {code(g, t)} | {label(g, t)} | {' → '.join(path) if path else '*(category)*'} |")

    for cls, title in ((KRIM.ClearanceState, "Clearance states"), (KRIM.LocationRelevance, "Location relevance")):
        out += ["", f"## {title}", "", "| code | label | definition |", "|---|---|---|"]
        for c in sorted(g.subjects(RDF.type, cls), key=lambda c: code(g, c)):
            out.append(f"| {code(g, c)} | {label(g, c)} | {g.value(c, SKOS.definition)} |")
    out.append("")
    return "\n".join(out)


def main():
    path = TESTS / "sample-data.md"
    path.write_text(render(), encoding="utf-8")
    print(f"wrote {path}")


if __name__ == "__main__":
    main()
