"""Export the data dictionary for readers.

    .venv/bin/python scripts/generate_dictionary.py          # CSV, Excel, Quarto source
    .venv/bin/python scripts/generate_dictionary.py --pdf    # ... and render the PDF

Outputs (all generated, never edited by hand):
  db/data-dictionary.csv       machine-readable, one row per column
  db/data-dictionary.xlsx      for review: filterable, with an empty Comments column
  docs/data-dictionary.qmd     -> docs/data-dictionary.pdf with --pdf
The same rows are in the database table meta_column.
"""
import csv
import io
import subprocess
import sys

from common import DB_DIR, ROOT
from rdflib import OWL, RDFS, SKOS, Literal
from rdflib.namespace import DCTERMS

from dictionary import FIELDS, build_rows, clean, codelists, context, curie, lang_value, table_definitions


# Territorial codelists maintained by ČSÚ: the dictionary points to them instead of listing them.
CZSO_CODELISTS = {
    "municipality": ("municipalities and military training areas", 43),
    "orp_area": ("ORP areas (správní obvody obcí s rozšířenou působností)", 65),
    "okres": ("okresy", 101),
    "kraj": ("kraje", 100),
}

def deprecated_terms(ctx, rows) -> list[dict]:
    """Deprecated ontology terms, their replacements, and whether a column still realises them."""
    g, out = ctx.onto, []
    used = {r["property_iri"] for r in rows}
    for t in sorted(g.subjects(OWL.deprecated, Literal(True)), key=str):
        out.append({
            "term": curie(t), "label_en": lang_value(g, t, RDFS.label, "en"),
            "replaced_by": ", ".join(sorted(curie(r) for r in g.objects(t, DCTERMS.isReplacedBy))),
            "note": clean(lang_value(g, t, SKOS.editorialNote, "en")),
            "column": ", ".join(f"{r['table_name']}.{r['column_name']}" for r in rows if r["property_iri"] == str(t)),
        })
    return out

DOCS = ROOT / "docs"


def to_csv(rows) -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=[f for f, _, _ in FIELDS], lineterminator="\n")
    w.writeheader()
    w.writerows({f: r.get(f, "") for f, _, _ in FIELDS} for r in rows)
    return buf.getvalue()


def to_xlsx(rows, codes, ctx, path):
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill

    wb = Workbook()
    head_font, head_fill = Font(bold=True, color="FFFFFF"), PatternFill("solid", fgColor="36444E")
    wrap = Alignment(wrap_text=True, vertical="top")

    def sheet(ws, header, data, widths):
        ws.append(header)
        for row in data:
            ws.append(row)
        for cell in ws[1]:
            cell.font, cell.fill = head_font, head_fill
        for row in ws.iter_rows(min_row=2):
            for cell in row:
                cell.alignment = wrap
        for i, w in enumerate(widths, start=1):
            ws.column_dimensions[ws.cell(1, i).column_letter].width = w
        ws.freeze_panes = "C2"
        ws.auto_filter.ref = ws.dimensions

    ws = wb.active
    ws.title = "Columns"
    widths = {"definition_en": 60, "scope_note_en": 50, "business_rule_en": 45, "value_domain": 35,
              "object_class_iri": 30, "property_iri": 30}
    sheet(ws, [t for _, t, _ in FIELDS] + ["Comments", "Agree? (yes/no)"],
          [[r.get(f, "") for f, _, _ in FIELDS] + ["", ""] for r in rows],
          [widths.get(f, 18) for f, _, _ in FIELDS] + [40, 12])

    ws = wb.create_sheet("Codelists")
    sheet(ws, ["Codelist", "Code", "Label (cs)", "Label (en)", "Broader code", "Definition", "Comments"],
          [[name, i["code"], i["label_cs"], i["label_en"], i["broader"], i["definition_en"], ""]
           for name, items in codes.items() if name not in CZSO_CODELISTS for i in items],
          [20, 8, 40, 45, 10, 60, 40])

    ws = wb.create_sheet("Deprecated")
    sheet(ws, ["Term", "Label (en)", "Replaced by", "Note", "Still a column"],
          [[d["term"], d["label_en"], d["replaced_by"], d["note"], d["column"]] for d in deprecated_terms(ctx, rows)],
          [28, 24, 45, 70, 30])

    ws = wb.create_sheet("Fields")
    sheet(ws, ["Field", "Title", "Generated from"], [list(f) for f in FIELDS], [22, 22, 70])

    ws = wb.create_sheet("About")
    for row in (["Data dictionary of the Kriminalita database"],
                ["Ontology release", ctx.version], ["Ontology modified", ctx.modified],
                ["Generated by", "scripts/generate_dictionary.py from ontology/*.ttl and ontology/shapes.ttl"],
                ["Do not edit", "Return comments in the Comments columns; changes are made in the ontology."]):
        ws.append(row)
    ws.column_dimensions["A"].width, ws.column_dimensions["B"].width = 22, 90
    wb.properties.creator = "onto-db-poc"
    wb.save(path)


def esc(s) -> str:
    s = str(s or "")
    for a, b in (("\\", "\\\\"), ("|", "\\|"), ("$", "\\$"), ("^", "\\^"), ("*", "\\*"), ("<", "\\<"), ("_", "\\_")):
        s = s.replace(a, b)
    return s


def code(s) -> str:
    return f"`{s}`" if s else ""


def to_qmd(rows, codes, ctx) -> str:
    tdefs = table_definitions(ctx)
    by_table = {}
    for r in rows:
        by_table.setdefault(r["table_name"], []).append(r)
    o = [
        "---",
        'title: "Data dictionary"',
        f'subtitle: "Kriminalita database, ontology release {ctx.version} ({ctx.modified})"',
        "format:",
        "  pdf:",
        "    documentclass: scrartcl",
        "    papersize: a4",
        "    toc: true",
        "    toc-depth: 2",
        "    number-sections: true",
        "    colorlinks: true",
        '    mainfont: "Noto Serif"',
        '    sansfont: "Noto Sans"',
        '    monofont: "Noto Sans Mono"',
        "    fontsize: 9pt",
        "    geometry: margin=2cm",
        "---",
        "",
        "<!-- GENERATED by scripts/generate_dictionary.py - do not edit. -->",
        "",
        "# About this dictionary",
        "",
        "Every column of the Kriminalita SQLite database is described here as a *data element*",
        "(ISO/IEC 11179): an **object class** (the ontology class the table realises), a",
        "**property** (the ontology property the column realises) and a **value domain**",
        "(type, range, allowed codes). The dictionary is generated from the ontology",
        "(`ontology/kriminalita.ttl`, `ontology/reference/`) and the SHACL shapes",
        "(`ontology/shapes.ttl`); it is never edited by hand. The same content is in the",
        "database table `meta_column`, in `db/data-dictionary.csv`, and, for review with a",
        "*Comments* column, in `db/data-dictionary.xlsx`.",
        "",
        "Where a column realises a generic reused property (e.g. `dcterms:identifier`), its",
        "definition is a local data-element definition stated on the shape, so that every",
        "column has a domain-specific meaning.",
        "",
        "| Field | Generated from |",
        "|---|---|",
    ]
    o += [f"| {esc(t)} | {esc(src)} |" for _, t, src in FIELDS]
    o += ["", ": Dictionary fields and their sources {tbl-colwidths=\"[30,70]\"}", "",
          "# Tables", "", "| Table | Realises | Columns |", "|---|---|---|"]
    o += [f"| `{t}` | {esc(tdefs[t][0])} | {len(rs)} |" for t, rs in by_table.items()]
    o += ["", ": Tables {tbl-colwidths=\"[30,55,15]\"}", ""]

    for t, rs in by_table.items():
        label, definition, scope = tdefs[t]
        o += ["\\newpage", "", f"# Table `{t}`", "", f"**Realises:** {esc(label)} (`{curie(rs[0]['object_class_iri'])}`)", "",
              esc(definition), ""]
        if scope:
            o += [f"*Not to be confused with / scope:* {esc(scope)}", ""]
        o += ["| Column | Data element | SQL type | Null | Key |", "|---|---|---|---|---|"]
        o += [f"| `{r['column_name']}` | {esc(r['data_element_en'])} | {r['sql_type']} | {r['nullable']} | {esc(r['key'])} |"
              for r in rs]
        o += ["", f": Columns of {t} {{tbl-colwidths=\"[28,32,12,8,20]\"}}", ""]
        for r in rs:
            o += [f"## `{t}.{r['column_name']}`: {esc(r['data_element_en'])}", "",
                  "| | |", "|---|---|"]
            details = [
                ("Czech name", esc(r["data_element_cs"])),
                ("Definition", esc(r["definition_en"])),
                ("Scope note", esc(r["scope_note_en"])),
                ("Property", f"{esc(r['property'])} {code(curie(r['property_iri']))}" if r["property_iri"] else esc(r["property"])),
                ("Value domain", esc(r["value_domain"])),
                ("Cardinality", r["cardinality"]),
                ("Business rule", esc(r["business_rule_en"])),
                ("Source field (CSV)", code(r["source_field"])),
                ("Status", esc(r["status"])),
            ]
            o += [f"| **{k}** | {v} |" for k, v in details if v]
            o += ["", ": {tbl-colwidths=\"[22,78]\"}", ""]

    dep = deprecated_terms(ctx, rows)
    if dep:
        o += ["\\newpage", "", "# Appendix: deprecated terms", "",
              "Ontology terms that are deprecated (`owl:deprecated`): kept, never deleted, so that",
              "older data and documents stay interpretable, but not to be used for new data. The",
              "business glossary lists current terms only.", "",
              "| Term | Replaced by | Still a column | Note |", "|---|---|---|---|"]
        o += [f"| {code(d['term'])} ({esc(d['label_en'])}) | {esc(d['replaced_by'])} | "
              f"{code(d['column']) if d['column'] else 'no'} | {esc(d['note'])} |" for d in dep]
        o += ["", ": Deprecated terms {tbl-colwidths=\"[24,24,16,36]\"}", ""]

    o += ["\\newpage", "", "# Appendix: codelists", "",
          "Allowed values of the codelist columns, from the SKOS reference data. Labels in",
          "Czech come from the publisher; English labels and definitions are maintained in",
          "`ontology/reference/codelist-texts.csv`.", ""]
    for name, items in codes.items():
        o += [f"## `{name}`", ""]
        if name in CZSO_CODELISTS:  # a standard codelist: point to it instead of listing it
            what, kodcis = CZSO_CODELISTS[name]
            o += [f"{len(items)} {what}: the standard codelist of the Czech Statistical Office, ČSÚ codelist",
                  f"{kodcis} (<https://apl2.czso.cz/iSMS/cisdet.jsp?kodcis={kodcis}>); RÚIAN uses the same",
                  "codes. Not listed here.", ""]
            continue
        if any(i["broader"] for i in items):
            o += ["| Code | Label (cs) | Label (en) | Broader |", "|---|---|---|---|"]
            o += [f"| {i['code']} | {esc(i['label_cs'])} | {esc(i['label_en'])} | {i['broader']} |" for i in items]
            o += ["", f": {name} {{tbl-colwidths=\"[8,40,42,10]\"}}", ""]
        else:
            o += ["| Code | Label (cs) | Label (en) | Definition |", "|---|---|---|---|"]
            o += [f"| {i['code']} | {esc(i['label_cs'])} | {esc(i['label_en'])} | {esc(i['definition_en'])} |" for i in items]
            o += ["", f": {name} {{tbl-colwidths=\"[8,22,20,50]\"}}", ""]
    return "\n".join(o)


def outputs():
    """Return {path: text} of the text outputs (used by validate.py for drift checks)."""
    ctx = context()
    rows, codes = build_rows(ctx), codelists(ctx)
    return ctx, rows, codes, {
        DB_DIR / "data-dictionary.csv": to_csv(rows),
        DOCS / "data-dictionary.qmd": to_qmd(rows, codes, ctx),
    }


def main():
    ctx, rows, codes, texts = outputs()
    for path, text in texts.items():
        path.parent.mkdir(exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    xlsx = DB_DIR / "data-dictionary.xlsx"
    to_xlsx(rows, codes, ctx, xlsx)
    print(f"wrote {xlsx.relative_to(ROOT)}")
    if "--pdf" in sys.argv:
        subprocess.run(["quarto", "render", str(DOCS / "data-dictionary.qmd")], check=True)


if __name__ == "__main__":
    main()
