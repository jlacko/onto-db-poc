"""Rebuild the numeric index of competency questions in ontology/competency-questions.md.

    .venv/bin/python scripts/cq_index.py

The questions are grouped by topic, so their numbers are not in file order; the
numbers are identifiers (query files, reports and documents refer to them) and are
never reused. The index lists them in numeric order with section and status. It
lives between the markers <!-- cq-index:start --> and <!-- cq-index:end --> and is
the only generated part of the file; validate.py checks it is current.
"""
import re

from common import ONTO, TESTS

PATH = ONTO / "competency-questions.md"
START, END = "<!-- cq-index:start -->", "<!-- cq-index:end -->"


def build(text: str) -> str:
    rows, section = [], ""
    for line in text.splitlines():
        if line.startswith("## "):
            section = line[3:].strip()
        m = re.match(r"^### (CQ\d+): (.*)$", line)
        if m:
            rows.append((m.group(1), m.group(2), section))
    out = [START, "", "| CQ | Question | Section | Answer | Tested in |", "|---|---|---|---|---|"]
    for cq, title, sec in sorted(rows, key=lambda r: int(r[0][2:])):
        hand = "✍" in title
        title = title.replace("✍ your answer", "").strip()
        body = text[text.index(f"### {cq}:"):]
        nxt = re.search(r"^#{2,3} ", body[4:], re.M)
        body = body[: nxt.start() + 4] if nxt else body
        layers = [x for x, ext in (("SPARQL", "rq"), ("SQL", "sql")) if (TESTS / "cq" / f"{cq}.{ext}").exists()]
        if "```expected" not in body:
            answer, tested = "gap (not answerable)", "—"
        else:
            answer = "domain expert ✍" if hand else "pre-filled"
            tested = " + ".join(layers)
        letter = sec.split(".")[0] if "." in sec[:3] else sec
        out.append(f"| {cq} | {title} | {letter} | {answer} | {tested} |")
    secs = []
    for line in text.splitlines():
        m = re.match(r"^## ([A-Z])\. (.*)$", line)
        if m and m.group(1) not in [x[0] for x in secs]:
            secs.append((m.group(1), m.group(2).split(" (")[0].replace("✍", "").strip()))
    out += ["", "Sections: " + "; ".join(f"**{l}** {name.lower()}" for l, name in secs) + ".", "", END]
    return "\n".join(out)


def apply(text: str) -> str:
    block = build(text)
    if START in text:
        return re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    anchor = "## A. "
    return text.replace(anchor, "## Index\n\nGENERATED by `scripts/cq_index.py` (numbers are identifiers, "
                                "so they are not in file order).\n\n" + block + "\n\n" + anchor, 1)


def main():
    text = PATH.read_text(encoding="utf-8")
    PATH.write_text(apply(text), encoding="utf-8")
    print(f"index rebuilt in {PATH}")


if __name__ == "__main__":
    main()
